"""Writes (or with --check, verifies) .env.example from the engine variables and from the secrets
that bundled plugins and bundled scripts declare. Private plugins are never read."""

import sys
from pathlib import Path

from homelab.envvars import ENGINE_ENV, UNV_ENV
from homelab.registry import discover

ROOT = Path(__file__).resolve().parent.parent


def build() -> str:
    found = discover(ROOT / "no-private-plugins", [ROOT / "src" / "homelab" / "scripts"])
    declared: dict[str, list[str]] = {}
    for name, plugin in sorted(found.plugins.items()):
        for secret in plugin.manifest.secrets:
            declared.setdefault(secret, []).append(name)
    lines = [
        "# Generated by tools/gen_env_example.py. Do not edit; run the script after changing a plugin.",
        "#",
        "# Sample environment for homelab-automation.",
        "# RECOMMENDED: keep secrets in UnENVerse (docs/UNV.md). The engine then runs under `unv exec` and you",
        "# set none of the secrets below.",
        "# FALLBACK: copy this file to .env, run `chmod 600 .env`, and fill in only what your plugins need.",
        "# The engine refuses a .env that other users can read, and reads only the names plugins declare.",
        "",
        "# --- engine ---",
    ]
    lines += [f"# {name}=    # {text}" for name, (group, text) in ENGINE_ENV.items() if group == "engine"]
    lines += ["", "# --- internal, set by the engine, never by you ---"]
    lines += [f"# {name}    # {text}" for name, (group, text) in ENGINE_ENV.items() if group == "internal"]
    lines += ["", "# --- UnENVerse, only when unv must authenticate by itself (scheduled runs); see docs/UNV.md ---"]
    lines += [f"# {name}=    # {text}" for name, text in UNV_ENV.items()]
    lines += ["", "# --- secrets declared by bundled plugins and scripts ---"]
    if declared:
        lines += [f"{name}=    # {', '.join(users)}" for name, users in declared.items()]
    else:
        lines.append("# none yet: a plugin lists its secrets in its manifest, and they appear here")
    lines += [
        "",
        "# --- secrets of your own private plugins: one line per name your manifests declare ---",
        "# MY_PLUGIN_API_KEY=",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    path = ROOT / ".env.example"
    text = build()
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            print("stale .env.example, run tools/gen_env_example.py")
            return 1
        return 0
    path.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
